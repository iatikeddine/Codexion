#include "codexion.h"

int	is_valid_number(const char *num)
{
	if (num[0] == '\0')
		return 0;
	size_t	i = 0;

	while (num[i] != '\0')
	{
		if (num[i] < '0' || num[i] > '9')
			return 0;
		i++;
	}
	return 1;
}
